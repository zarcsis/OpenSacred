/// The runs `runs` as each type's image.
fn expand(runs: &[(u16, u16, u32)]) -> Vec<(u32, u32)> {
    runs.iter()
        .flat_map(|&(first, last, image)| (first..=last).map(move |t| (u32::from(t), image)))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_runs_cover_467_types_in_order() {
        let images = images();
        assert_eq!(images.len(), 467);
        assert!(images.windows(2).all(|pair| pair[0].0 < pair[1].0));
        // The Seraphim's, the goblin warrior's and the two that the switch compares alone.
        let image = |creature| {
            images
                .iter()
                .find(|&&(t, _)| t == creature)
                .map(|&(_, i)| i)
        };
        assert_eq!(image(1), Some(964));
        assert_eq!(
            [image(0x20).is_some(), image(0x17E2).is_some()],
            [true, true]
        );
        assert_eq!(image(10), None);
        // The column's: 373 types, the heroes' as the bar knows them.
        let column = column_images();
        assert_eq!(column.len(), 373);
        let heroes: Vec<u32> = (1..=9)
            .filter_map(|t| column.iter().find(|&&(c, _)| c == t).map(|&(_, i)| i))
            .collect();
        assert_eq!(
            heroes,
            [1255, 1257, 1256, 1260, 1261, 1259, 1259, 1438, 1437]
        );
    }
}
